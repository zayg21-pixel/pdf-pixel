namespace PdfPixel.Forms;

/// <summary>
/// Represents keyboard keys for form field interactions.
/// </summary>
public enum FormFieldKey
{
    /// <summary>
    /// Unknown or unsupported key.
    /// </summary>
    Unknown,

    /// <summary>
    /// Enter (Return) key.
    /// </summary>
    Enter,

    /// <summary>
    /// Tab key.
    /// </summary>
    Tab,

    /// <summary>
    /// Escape key.
    /// </summary>
    Escape,

    /// <summary>
    /// Backspace key.
    /// </summary>
    Backspace,

    /// <summary>
    /// Delete key.
    /// </summary>
    Delete,

    /// <summary>
    /// Left arrow key.
    /// </summary>
    Left,

    /// <summary>
    /// Right arrow key.
    /// </summary>
    Right,

    /// <summary>
    /// Up arrow key.
    /// </summary>
    Up,

    /// <summary>
    /// Down arrow key.
    /// </summary>
    Down,

    /// <summary>
    /// Home key.
    /// </summary>
    Home,

    /// <summary>
    /// End key.
    /// </summary>
    End,

    /// <summary>
    /// Page Up key.
    /// </summary>
    PageUp,

    /// <summary>
    /// Page Down key.
    /// </summary>
    PageDown,

    /// <summary>
    /// Space bar.
    /// </summary>
    Space
}
