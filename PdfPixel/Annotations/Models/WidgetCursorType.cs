namespace PdfPixel.Annotations.Models;

/// <summary>
/// Cursor types for widget annotations.
/// </summary>
public enum WidgetCursorType
{
    /// <summary>
    /// Default arrow cursor.
    /// </summary>
    Arrow,

    /// <summary>
    /// Hand cursor for clickable widgets.
    /// </summary>
    Hand,

    /// <summary>
    /// Text input cursor (I-beam) for text fields.
    /// </summary>
    IBeam
}
